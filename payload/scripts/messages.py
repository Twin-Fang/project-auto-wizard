#!/usr/bin/env python3
"""
messages.py — message catalog and language lookup shared by the installed
workflow scripts (stdlib only).

This script is copied into user repos (.github/scripts/) by project-auto-wizard.
Everything a workflow or script prints for people to read (PR comments, release
summaries, log lines, AI prompts) is looked up here by key, so the wording
follows the `language` value in version.yml (en | ko, default en).

Language resolution (first match wins):
    1. env PROJECT_AUTO_WIZARD_LANG   (same variable the installer honors)
    2. `language:` in the first version.yml that has it, looking in: ./version.yml, the repo root
       relative to this script (../../version.yml), $GITHUB_WORKSPACE/version.yml
       (steps with a working-directory in a monorepo do not run at the repo root)
    3. "en"

Python usage:
    from messages import t
    t("issue_helper.branch_title")
    t("changelog.count", n=3)          # {n} placeholders are replaced

Command line (used from bash and actions/github-script):
    messages.py get KEY [name=value ...]   print one message (trailing newline)
    messages.py dump PREFIX                print {key: template} JSON for keys with the prefix
    messages.py lang                       print the resolved language

A key missing from the selected language falls back to English; a key missing
everywhere is returned as-is so the gap is visible instead of crashing a run.
Placeholders are `{name}`; unknown placeholders and any other braces stay as written.
"""

import json
import os
import re
import sys

SUPPORTED = ("en", "ko")
DEFAULT = "en"
LANG_ENV = "PROJECT_AUTO_WIZARD_LANG"

_PLACEHOLDER = re.compile(r"\{(\w+)\}")
_LANG_LINE = re.compile(r"^language:\s*(.+)")


def normalize_language(value):
    """Trim and lowercase, like the CLI's normalizeLanguage (so ' KO ' == 'ko')."""
    return str(value if value is not None else "").strip().lower()


def parse_saved_language(text):
    """`language:` value from version.yml text, normalized ('' when absent).

    Mirrors the CLI's parseExisting(): top-level line only, `#` comment lines skipped,
    first match wins, trailing ` # comment` and quotes removed. The whole value is kept,
    so 'ko_KR' is unsupported here exactly as it is in the CLI."""
    for line in str(text or "").split("\n"):
        if line.startswith("#"):
            continue
        m = _LANG_LINE.match(line)
        if m:
            return normalize_language(re.sub(r"\s+#.*$", "", m.group(1)).replace('"', "").replace("'", ""))
    return ""


def _version_yml_candidates(version_yml):
    """Where to look for version.yml: cwd, then the repo root relative to this script, then $GITHUB_WORKSPACE.

    Steps with a working-directory (monorepo) or a scripts run from a subfolder are not at the repo root;
    the installed script lives in <root>/.github/scripts, so the root is two levels up."""
    candidates = [version_yml, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "version.yml")]
    workspace = os.environ.get("GITHUB_WORKSPACE", "")
    if workspace:
        candidates.append(os.path.join(workspace, "version.yml"))
    return candidates


def _resolve_language(version_yml="version.yml"):
    """(language, ignored): the resolved language and the unsupported value that was skipped on the way ('' if none).

    Same rules as the CLI (src/i18n): values are normalized and only supported ones count.
    Unlike the CLI, an unsupported env value is ignored instead of aborting, because a
    failing message lookup must never break a workflow step. An unreadable or
    non-UTF-8 version.yml is skipped; the first file that has a `language:` line decides."""
    env = normalize_language(os.environ.get(LANG_ENV))
    if env in SUPPORTED:
        return env, ""
    ignored = env
    saved = ""
    for path in _version_yml_candidates(version_yml):
        try:
            # errors="replace" keeps ASCII keys readable in a cp949/latin-1 file, as the CLI's utf8 read does
            with open(path, encoding="utf-8", errors="replace") as f:
                saved = parse_saved_language(f.read())
        except (OSError, ValueError):
            continue
        # A file without a language line says nothing; keep looking (monorepo subfolder copies etc.)
        if saved:
            break
    if saved in SUPPORTED:
        return saved, ignored
    return DEFAULT, ignored or saved


def get_language(version_yml="version.yml"):
    """Resolve the message language: env -> version.yml -> default."""
    return _resolve_language(version_yml)[0]


def template(key, lang=None):
    """Raw template for `key` in `lang` (English fallback, then the key itself)."""
    lang = lang or get_language()
    return CATALOG.get(lang, {}).get(key) or CATALOG[DEFAULT].get(key) or key


def render(text, params):
    """Replace `{name}` placeholders from params; leave unknown ones untouched."""
    return _PLACEHOLDER.sub(lambda m: str(params[m.group(1)]) if m.group(1) in params else m.group(0), text)


def t(key, lang=None, **params):
    """Look up `key` and fill placeholders."""
    return render(template(key, lang), params)


def tn(key, n, lang=None, **params):
    """Like t(), but uses `<key>_one` when n == 1 and that key exists (English singular).
    {n} is always filled in, so languages without plural forms just define `<key>` alone."""
    if n == 1 and f"{key}_one" in CATALOG[DEFAULT]:
        key = f"{key}_one"
    return t(key, lang, n=n, **params)


def dump(prefix, lang=None):
    """{key: raw template} for every key starting with `prefix`, English-filled."""
    lang = lang or get_language()
    keys = [k for k in CATALOG[DEFAULT] if k.startswith(prefix)]
    return {k: template(k, lang) for k in keys}


def use_utf8_output():
    """Print UTF-8 regardless of the console code page (Windows defaults to cp1252) and never crash on it."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


def main(argv):
    use_utf8_output()
    if len(argv) >= 2 and argv[0] == "get":
        params = dict(a.split("=", 1) for a in argv[2:] if "=" in a)
        print(t(argv[1], **params))
        return 0
    if len(argv) == 2 and argv[0] == "dump":
        print(json.dumps(dump(argv[1]), ensure_ascii=False))
        return 0
    if argv == ["lang"]:
        lang, ignored = _resolve_language()
        if ignored:
            # stdout stays the bare language code (callers capture it); the notice goes to stderr
            print(t("lang.fallback", lang, value=ignored, lang_code=lang, supported=", ".join(SUPPORTED)), file=sys.stderr)
        print(lang)
        return 0
    print("usage: messages.py get KEY [name=value ...] | dump PREFIX | lang", file=sys.stderr)
    return 2


